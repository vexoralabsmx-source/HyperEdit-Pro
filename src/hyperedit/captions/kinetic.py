"""Kinetic typography compiler generating dynamic word-level ASS subtitle scripts."""

import re
from typing import List

from hyperedit.captions.formats import (
    alignment_to_ass_numpad,
    hex_to_ass_color,
    ms_to_ass_time,
)
from hyperedit.captions.models import (
    KineticAnimationMode,
    SubtitleCue,
    SubtitleTrack,
    WordTimestamp,
)


def estimate_word_timestamps(cue: SubtitleCue) -> List[WordTimestamp]:
    """Estimate word-level boundaries proportionally based on character length when raw ASR timestamps are absent."""
    words = cue.text.strip().split()
    if not words:
        return []

    weights = [max(1, len(re.sub(r"[^\w]", "", w))) for w in words]
    total_weight = sum(weights)
    total_dur = cue.duration_ms

    word_items: List[WordTimestamp] = []
    current_ms = cue.start_ms

    for idx, (word, weight) in enumerate(zip(words, weights)):
        if idx == len(words) - 1:
            w_end = cue.end_ms
        else:
            share = int(round((weight / total_weight) * total_dur))
            w_end = min(cue.end_ms, current_ms + max(120, share))

        word_items.append(
            WordTimestamp(
                word=word,
                start_ms=current_ms,
                end_ms=w_end,
                confidence=0.85,
            )
        )
        current_ms = w_end

    return word_items


class KineticTypographyCompiler:
    """Compiles subtitle tracks with word-level kinetic animations into Advanced SubStation Alpha scripts."""

    @classmethod
    def compile_ass(
        cls,
        track: SubtitleTrack,
        width: int = 1920,
        height: int = 1080,
        title: str = "HyperEdit Pro Kinetic Typography",
    ) -> str:
        """Compile a SubtitleTrack into an ASS script containing kinetic typography events."""
        style = track.default_style
        primary_ass = hex_to_ass_color(style.primary_color_hex)
        highlight_ass = hex_to_ass_color(style.highlight_color_hex)
        outline_ass = hex_to_ass_color(style.outline_color_hex)
        back_ass = hex_to_ass_color(
            style.background_box_color_hex if style.background_box else style.shadow_color_hex,
            default_alpha=128 if style.background_box else 0,
        )

        bold_val = -1 if style.bold else 0
        italic_val = -1 if style.italic else 0
        border_style = 3 if style.background_box else 1
        align_code = alignment_to_ass_numpad(style.alignment)

        header = f"""[Script Info]
; Kinetic Typography script generated by HyperEdit Pro v2.0
Title: {title}
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
PlayResX: {width}
PlayResY: {height}

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,{style.font_name},{style.font_size},{primary_ass},{highlight_ass},{outline_ass},{back_ass},{bold_val},{italic_val},0,0,100,100,{style.letter_spacing},0,{border_style},{style.outline_width},{style.shadow_offset},{align_code},{style.margin_h},{style.margin_h},{style.margin_v},1
Style: Active,{style.font_name},{style.font_size},{highlight_ass},{primary_ass},{outline_ass},{back_ass},{bold_val},{italic_val},0,0,110,110,{style.letter_spacing},0,{border_style},{style.outline_width},{style.shadow_offset},{align_code},{style.margin_h},{style.margin_h},{style.margin_v},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
        dialogue_lines: List[str] = []
        track.sort_cues()

        mode = style.animation_mode

        for cue in track.cues:
            words = cue.words if cue.words else estimate_word_timestamps(cue)
            if not words or mode == KineticAnimationMode.NONE:
                # Fallback to standard static line
                s_str = ms_to_ass_time(cue.start_ms)
                e_str = ms_to_ass_time(cue.end_ms)
                txt = cue.text.upper() if style.all_caps else cue.text
                formatted = txt.replace("\r\n", r"\N").replace("\n", r"\N")
                dialogue_lines.append(f"Dialogue: 0,{s_str},{e_str},Default,,0,0,0,,{formatted}")
                continue

            if mode in (KineticAnimationMode.KARAOKE_HIGHLIGHT, KineticAnimationMode.POP_SCALE):
                # Word-by-word active highlight or pop emphasis
                raw_words = [w.word.upper() if style.all_caps else w.word for w in words]

                # Pre-cue neutral interval if first word starts after cue start
                if words[0].start_ms > cue.start_ms:
                    s_str = ms_to_ass_time(cue.start_ms)
                    e_str = ms_to_ass_time(words[0].start_ms)
                    dialogue_lines.append(
                        f"Dialogue: 0,{s_str},{e_str},Default,,0,0,0,,{' '.join(raw_words)}"
                    )

                for w_idx, w in enumerate(words):
                    s_str = ms_to_ass_time(w.start_ms)
                    e_str = ms_to_ass_time(w.end_ms)
                    if w.end_ms <= w.start_ms:
                        continue

                    # Construct sentence with the current word highlighted
                    tokens: List[str] = []
                    for t_idx, token_text in enumerate(raw_words):
                        if t_idx == w_idx:
                            if mode == KineticAnimationMode.POP_SCALE:
                                tokens.append(r"{\fscx115\fscy115\c" + highlight_ass + r"&}" + token_text + r"{\r}")
                            else:
                                tokens.append(r"{\c" + highlight_ass + r"&}" + token_text + r"{\r}")
                        else:
                            tokens.append(token_text)

                    line_text = " ".join(tokens)
                    dialogue_lines.append(f"Dialogue: 0,{s_str},{e_str},Default,,0,0,0,,{line_text}")

                # Post-cue neutral interval if last word ends before cue end
                if words[-1].end_ms < cue.end_ms:
                    s_str = ms_to_ass_time(words[-1].end_ms)
                    e_str = ms_to_ass_time(cue.end_ms)
                    dialogue_lines.append(
                        f"Dialogue: 0,{s_str},{e_str},Default,,0,0,0,,{' '.join(raw_words)}"
                    )

            elif mode == KineticAnimationMode.WORD_REVEAL:
                # Progressive word accumulation
                raw_words = [w.word.upper() if style.all_caps else w.word for w in words]
                for w_idx, w in enumerate(words):
                    s_str = ms_to_ass_time(w.start_ms)
                    e_str = ms_to_ass_time(w.end_ms)
                    visible_slice = " ".join(raw_words[: w_idx + 1])
                    dialogue_lines.append(f"Dialogue: 0,{s_str},{e_str},Default,,0,0,0,,{visible_slice}")

            elif mode == KineticAnimationMode.FADE_WORD:
                # Fade in / out transition on the whole cue
                s_str = ms_to_ass_time(cue.start_ms)
                e_str = ms_to_ass_time(cue.end_ms)
                txt = cue.text.upper() if style.all_caps else cue.text
                formatted = txt.replace("\r\n", r"\N").replace("\n", r"\N")
                dialogue_lines.append(
                    r"Dialogue: 0," + f"{s_str},{e_str},Default,,0,0,0,,{{\\fad(150,150)}}{formatted}"
                )

            elif mode == KineticAnimationMode.SLIDE_UP:
                # Slide up from bottom using \move tag
                s_str = ms_to_ass_time(cue.start_ms)
                e_str = ms_to_ass_time(cue.end_ms)
                txt = cue.text.upper() if style.all_caps else cue.text
                formatted = txt.replace("\r\n", r"\N").replace("\n", r"\N")
                # Move vertical position upward by 25px
                target_y = height - style.margin_v
                start_y = target_y + 25
                x_pos = width // 2
                dialogue_lines.append(
                    r"Dialogue: 0,"
                    + f"{s_str},{e_str},Default,,0,0,0,,{{\\move({x_pos},{start_y},{x_pos},{target_y},0,120)\\fad(100,100)}}{formatted}"
                )

        return header + "\n".join(dialogue_lines) + "\n"

